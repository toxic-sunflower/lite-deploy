package builtin

import (
	"context"
	"fmt"
	"io/fs"
	"sort"
	"strings"
	"time"

	"github.com/toxic-sunflower/lite-deploy/internal/host"
	"github.com/toxic-sunflower/lite-deploy/internal/plugin"
)

// Caddy paths.
const (
	caddyfile    = "/etc/caddy/Caddyfile"
	caddyConfDir = "/etc/caddy/conf.d"
	caddyMark    = "# managed-by: lite-deploy"
)

// Caddy is the `caddy` plugin: incoming (HTTP) traffic for projects.
type Caddy struct{}

func (Caddy) Name() string       { return "caddy" }
func (Caddy) Kind() string       { return "builtin" }
func (Caddy) Requires() []string { return nil }
func (Caddy) Description() string {
	return "incoming traffic: the Caddy web server, serves the project sites from " + caddyConfDir
}
func (Caddy) Commands() []plugin.Command {
	return []plugin.Command{
		{Name: "install", Help: "install Caddy and the main Caddyfile, start the service", Confirm: true},
		{Name: "status", Help: "Caddy state and connected sites"},
		{Name: "validate", Help: "check the Caddy configuration"},
		{Name: "reload", Help: "reload the configuration without stopping the sites", Confirm: true},
		{Name: "sites", Help: "project sites (files in " + caddyConfDir + ")"},
	}
}

// InstallCaddy installs Caddy (on Debian and Ubuntu from the official repository) and the main Caddyfile,
// which serves the project sites from /etc/caddy/conf.d, then starts the service.
func InstallCaddy(ctx context.Context, env plugin.Env, say Say) error {
	t := tools{ctx, env}
	m := t.manager()
	if m == "" {
		return plugin.Errorf("precondition_failed", "no package manager found (apt, dnf, zypper, pacman)")
	}
	if !t.ok("caddy", "version") {
		say.say("Plugin caddy: installing Caddy...")
		switch m {
		case "apt":
			if err := t.caddyApt(); err != nil {
				return err
			}
		case "dnf":
			if err := t.must("dnf", "install", "-y", "-q", "dnf-command(copr)"); err != nil {
				return err
			}
			if err := t.must("dnf", "copr", "enable", "-y", "@caddy/caddy"); err != nil {
				return err
			}
			if err := t.install("caddy"); err != nil {
				return err
			}
		default:
			if err := t.install("caddy"); err != nil {
				return err
			}
		}
	}
	if err := env.FS.MkdirAll(caddyConfDir, fs.FileMode(0o755)); err != nil {
		return plugin.Errorf("io_error", "%v", err)
	}
	old, rerr := env.FS.ReadFile(caddyfile)
	if rerr != nil || !strings.Contains(string(old), caddyMark) {
		if rerr == nil {
			_ = env.FS.WriteFile(fmt.Sprintf("%s.bak.%s", caddyfile, time.Now().Format("20060102150405")), old, fs.FileMode(0o644))
		}
		body := caddyMark + "\n# Each project adds its own file " + caddyConfDir + "/<project>.caddy. Do not edit this file by hand.\nimport " + caddyConfDir + "/*.caddy\n"
		if err := env.FS.WriteFile(caddyfile, []byte(body), fs.FileMode(0o644)); err != nil {
			return plugin.Errorf("io_error", "%v", err)
		}
	}
	const placeholder = caddyConfDir + "/00-placeholder.caddy"
	if _, err := env.FS.Stat(placeholder); err != nil {
		if err := env.FS.WriteFile(placeholder, []byte("# placeholder so the import mask always finds a file\n"), fs.FileMode(0o644)); err != nil {
			return plugin.Errorf("io_error", "%v", err)
		}
	}
	if err := t.must("caddy", "validate", "--config", caddyfile, "--adapter", "caddyfile"); err != nil {
		return plugin.Errorf("step_failed", "the main Caddyfile failed validation: %v", err)
	}
	if err := t.must("systemctl", "enable", "--now", "caddy"); err != nil {
		return err
	}
	return t.must("systemctl", "reload", "caddy")
}

// caddyApt adds the official Caddy repository and installs the package (as in the official instructions).
func (t tools) caddyApt() error {
	if err := t.install("debian-keyring", "debian-archive-keyring", "apt-transport-https", "curl", "gnupg"); err != nil {
		return err
	}
	get := func(url string) ([]byte, error) {
		res, err := t.env.Runner.Run(t.ctx, host.Cmd{Name: "curl", Args: []string{"-fsSL", "--proto", "=https", "--tlsv1.2", url}, Timeout: 2 * time.Minute})
		if err != nil {
			return nil, plugin.Errorf("step_failed", "curl: %v", err)
		}
		if res.ExitCode != 0 {
			return nil, plugin.Errorf("step_failed", "could not download %s: %s", url, strings.TrimSpace(string(res.Stderr)))
		}
		return res.Stdout, nil
	}
	key, err := get("https://dl.cloudsmith.io/public/caddy/stable/gpg.key")
	if err != nil {
		return err
	}
	const keyring = "/usr/share/keyrings/caddy-stable-archive-keyring.gpg"
	res, err := t.env.Runner.Run(t.ctx, host.Cmd{Name: "gpg", Args: []string{"--dearmor", "--yes", "-o", keyring}, Stdin: key})
	if err != nil {
		return plugin.Errorf("step_failed", "gpg: %v", err)
	}
	if res.ExitCode != 0 {
		return plugin.Errorf("step_failed", "gpg --dearmor: %s", strings.TrimSpace(string(res.Stderr)))
	}
	list, err := get("https://dl.cloudsmith.io/public/caddy/stable/debian.deb.txt")
	if err != nil {
		return err
	}
	const listFile = "/etc/apt/sources.list.d/caddy-stable.list"
	if err := t.env.FS.WriteFile(listFile, list, fs.FileMode(0o644)); err != nil {
		return plugin.Errorf("io_error", "%v", err)
	}
	if err := t.env.FS.Chmod(keyring, fs.FileMode(0o644)); err != nil {
		return plugin.Errorf("io_error", "%v", err)
	}
	return t.install("caddy")
}

func (Caddy) Run(ctx context.Context, env plugin.Env, cmd string, args []string) (plugin.Output, error) {
	t := tools{ctx, env}
	if err := noArgs(args, cmd, "caddy"); err != nil {
		return plugin.Output{}, err
	}
	switch cmd {
	case "install":
		if err := InstallCaddy(ctx, env, nil); err != nil {
			return plugin.Output{}, err
		}
		return textOut("Caddy is installed and running.\n"), nil
	case "validate", "reload", "status", "sites":
		if !t.ok("caddy", "version") {
			e := plugin.Errorf("precondition_failed", "Caddy is not installed")
			e.Hint = "lite caddy install"
			return plugin.Output{}, e
		}
	default:
		return plugin.Output{}, plugin.Errorf("usage", "plugin caddy has no command %q", cmd)
	}
	switch cmd {
	case "validate":
		if err := t.must("caddy", "validate", "--config", caddyfile, "--adapter", "caddyfile"); err != nil {
			return plugin.Output{}, err
		}
		return textOut("Configuration is valid.\n"), nil
	case "reload":
		if err := t.must("caddy", "validate", "--config", caddyfile, "--adapter", "caddyfile"); err != nil {
			return plugin.Output{}, plugin.Errorf("step_failed", "the configuration failed validation, Caddy was not touched: %v", err)
		}
		if err := t.must("systemctl", "reload", "caddy"); err != nil {
			return plugin.Output{}, err
		}
		return textOut("Configuration reloaded.\n"), nil
	case "sites":
		sites := t.sites()
		return plugin.Output{Text: strings.Join(append(sites, ""), "\n"), Data: map[string]any{"sites": sites}}, nil
	}
	res, _ := t.run("caddy", "version")
	active := t.ok("systemctl", "is-active", "--quiet", "caddy")
	sites := t.sites()
	text := fmt.Sprintf("Caddy %s, service %s, sites: %d\n", strings.TrimSpace(string(res.Stdout)), map[bool]string{true: "running", false: "not working"}[active], len(sites))
	return plugin.Output{Text: text, Data: map[string]any{"version": strings.TrimSpace(string(res.Stdout)), "active": active, "sites": sites}}, nil
}

func (t tools) sites() []string {
	names, _ := t.env.FS.ReadDir(caddyConfDir)
	sites := []string{}
	for _, n := range names {
		if s, ok := strings.CutSuffix(n, ".caddy"); ok && !strings.HasPrefix(n, "00-") {
			sites = append(sites, s)
		}
	}
	sort.Strings(sites)
	return sites
}

func (Caddy) Check(ctx context.Context, env plugin.Env) []plugin.Finding {
	t := tools{ctx, env}
	if !t.ok("caddy", "version") {
		return []plugin.Finding{finding("caddy", "installed", plugin.LevelOK, "Caddy is not installed (not in use)", "")}
	}
	var out []plugin.Finding
	if t.ok("systemctl", "is-active", "--quiet", "caddy") {
		out = append(out, finding("caddy", "service", plugin.LevelOK, "the Caddy service is running", ""))
	} else {
		out = append(out, finding("caddy", "service", plugin.LevelFail, "the Caddy service is not running", "sudo systemctl enable --now caddy"))
	}
	if t.ok("caddy", "validate", "--config", caddyfile, "--adapter", "caddyfile") {
		out = append(out, finding("caddy", "config", plugin.LevelOK, "Caddy configuration is valid", ""))
	} else {
		out = append(out, finding("caddy", "config", plugin.LevelFail, "Caddy configuration does not pass validation", "lite caddy validate"))
	}
	if b, err := env.FS.ReadFile(caddyfile); err != nil || !strings.Contains(string(b), caddyMark) {
		out = append(out, finding("caddy", "caddyfile", plugin.LevelWarn, "the main Caddyfile is not managed by lite: project sites may not be served", "lite caddy install"))
	}
	return out
}

// Installed reports whether Caddy is on this server.
func (Caddy) Installed(ctx context.Context, env plugin.Env) bool {
	return tools{ctx, env}.ok("caddy", "version")
}
